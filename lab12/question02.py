#abs(): transforma números negativos em positivos e mantém os positivos. Exemplo:
distancia = abs(-7)
#bool(): avalia o valor de uma expressão ou dado e converte para true ou false. Exemplos:
print(bool("Python")) #true, pois a string contém texto
print(bool(0)) #false, pois o valor é zero.
#float(): converte um número ou uma string (texto) que representa um número em um valor decimal. Exemplo:
altura = float("1.75")
#input(): o programa lê a entrada digitada pelo usuário no teclado. Retorna sempre uma string (texto) Exemplo:
nome = input("Qual é o seu nome?")
#int(): converte um valor numerico ou string em um número inteiro. Exemplo:
idade = int("15")
#print(): exibe mensagens, resultados ou variáveis no terminal. Exemplo:
print("Olá, Camila! :)")
#str(): converte qualquer tipo de dado em objeto ou variável. Exemplo:
oi = str(10)
#type(): retorna o tipo de dado de um objeto ou variável. Exemplo:
tipo_dado = type(3.14) #(retorna float)
#__import__(): importa um módulo de forma dinâmica passando o nome como str. Exemplo:
rock = __import__("rock")